// Helper to filter time words by subcategory
export function getTimeWordsBySubCategory(subCat: string): WordItem[] {
  if (subCat === 'all' || subCat === 'time_words') {
    return TIME_WORDS;
  }
  return TIME_WORDS.filter(w => w.subCategories?.includes(subCat));
}

